#!/usr/bin/env python3
"""The single-player battle HUD placement, from the extracted Race UI layouts.

Writes include/mkw/battle_hud_layout.hpp (run after the race UI is extracted,
like tools/cook_race_hud.py's race_hud_layout.hpp):

- the team score (battle_total_point.brctr total_point_1 placing
  battle_team_score_red_vs_blue.brlyt: three red digits, the dash, three blue);
- the player's points or coins (point.brctr CtrlRacePoint_1_0 placing
  coin.brlyt's number);
- the +1/-1 popup (BattleAddPoint.brctr BattleAddPoint_1_0 placing
  battle_point_plus_minus_common.brlyt's sign beside a digit).

Rectangles are on the 400x240 canvas like race_hud_layout.hpp: the source's
832x456 widescreen canvas scaled by 240/456, each control anchored to its side.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / 'tools'), str(ROOT / 'vendor/gclib')]
from cook_race_hud import layout, variant

SCALE = 240 / 456


def main():
    ui = ROOT / 'assets/race-ui/Race/game_image'
    rects = {}

    def group(control, name, side):
        x, y, _, sx, sy = variant(ui / 'ctrl' / (control + '.brctr'), name)
        gx = (x + 416) * SCALE if side == 'left' else 400 - (416 - x) * SCALE if side == 'right' else 200 + x * SCALE
        return gx, (228 - y) * SCALE, sx * SCALE, sy * SCALE

    def rect(name, pose, pane, parent=None):
        gx, gy, sx, sy = pose
        px, py = (parent['x'], parent['y']) if parent else (0, 0)
        w, h = pane['w'] * pane['sx'] * sx, pane['h'] * pane['sy'] * sy
        rects[name] = [gx + (px + pane['x']) * sx - w / 2, gy - (py + pane['y']) * sy - h / 2, w, h]

    score = layout(ui / 'blyt/battle_team_score_red_vs_blue.brlyt')
    team = group('battle_total_point', 'total_point_1', 'right')
    for pane in ('red_a', 'red_b', 'red_c', 'hifun', 'blue_a', 'blue_b', 'blue_c'):
        rect('Team_' + pane, team, score[pane], score['race_null'])
    # total_point_3: the same score at the top centre, for the set's totals.
    totals = group('battle_total_point', 'total_point_3', 'center')
    for pane in ('red_a', 'red_b', 'red_c', 'hifun', 'blue_a', 'blue_b', 'blue_c'):
        rect('Total_' + pane, totals, score[pane], score['race_null'])
    coin = layout(ui / 'blyt/coin.brlyt')
    rect('Points', group('point', 'CtrlRacePoint_1_0', 'left'), coin['mario_text_red'], coin['race_null'])
    signs = layout(ui / 'blyt/battle_point_plus_minus_common.brlyt')
    popup = group('BattleAddPoint', 'BattleAddPoint_1_0', 'center')
    # The sign pane at the popup's centre; the digit follows on its right.
    sign = dict(signs['red_plus'], x=-signs['red_plus']['w'] * 0.5, y=0)
    rect('PopupSign', popup, sign)
    digit = dict(score['red_a'], x=score['red_a']['w'] * score['red_a']['sx'] * 0.5, y=0)
    rect('PopupDigit', popup, digit)

    lines = ['#pragma once', 'namespace mkw {',
             '// Generated by tools/battle_hud_layout.py from the original BRCTR/BRLYT.',
             '// x, y, w, h on the 400x240 canvas (right-anchored rectangles add display::WideExtra).',
             'struct BattleHudRect {float x,y,w,h;};']
    for name, values in rects.items():
        lines.append('inline constexpr BattleHudRect BattleHud%s{%s};' % (name, ','.join(f'{v:.4f}f' for v in values)))
    lines += ['}', '']
    out = ROOT / 'include/mkw/battle_hud_layout.hpp'
    out.write_text('\n'.join(lines))
    print(out)


if __name__ == '__main__':
    main()
