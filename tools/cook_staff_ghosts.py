#!/usr/bin/env python3
"""Staff ghost times for each course, read from the user's disc.

    .venv/Scripts/python tools/extract_disc.py <disc> data/extracted --prefix Race/TimeAttack/
    .venv/Scripts/python tools/cook_staff_ghosts.py

Reads the normal and expert staff ghosts (Race/TimeAttack/ghost1, ghost2: RKG
headers) and the time that unlocks each expert ghost (USA StaticR.rel, a u32
milliseconds table indexed by course id; build/itembox-retail.rel is the
disc's StaticR, extracted and verified by tools/release/build_cia.py). Writes
include/mkw/staff_ghosts.hpp in menu course order.
"""
import re, struct
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
GHOSTS = ROOT / 'data/extracted/Race/TimeAttack'
REL = ROOT / 'build/itembox-retail.rel'
UNLOCK_TABLE = 0x380f40  # USA RMCE01 StaticR.rel


def rkg(path):
    b = path.read_bytes()
    assert b[:4] == b'RKGD', path
    t = int.from_bytes(b[4:7], 'big')
    return b[7] >> 2, (t >> 17) * 60000 + ((t >> 10) & 0x7f) * 1000 + (t & 0x3ff)


def main():
    # Menu order to course id: the catalog's model lists are named by course id.
    ids = [int(n) for n in re.findall(r'models/course_(\d+)\.list', (ROOT / 'include/mkw/course_catalog.hpp').read_text())[:32]]
    staff, expert = {}, {}
    for i in range(32):
        c, ms = rkg(GHOSTS / f'ghost1/ghost1_comp_{i:02}.rkg'); staff[c] = ms
        c, ms = rkg(GHOSTS / f'ghost2/ghost2_comp_{i:02}.rkg'); expert[c] = ms
    rel = REL.read_bytes()
    unlock = struct.unpack_from('>32I', rel, UNLOCK_TABLE)
    for c in range(32):
        # Every unlock time lies between the course's two ghosts: a moved table fails here.
        assert expert[c] < unlock[c] <= staff[c], (c, expert[c], unlock[c], staff[c])
    rows = ',\n'.join('    {%d,%d,%d}' % (staff[c], expert[c], unlock[c]) for c in ids)
    (ROOT / 'include/mkw/staff_ghosts.hpp').write_text(
        '// Generated by tools/cook_staff_ghosts.py from the disc (RKG headers, StaticR).\n'
        '#pragma once\n#include <cstdint>\nnamespace mkw {\n'
        '// Milliseconds, in menu course order: the staff ghost, the expert staff\n'
        '// ghost, and the Time Trial time (or better) that unlocks the expert one.\n'
        'struct StaffGhostTimes {uint32_t staff,expert,unlock;};\n'
        'inline constexpr StaffGhostTimes StaffGhosts[32]={\n' + rows + '\n};\n}\n')
    print('staff ghosts: include/mkw/staff_ghosts.hpp')


if __name__ == '__main__':
    main()
